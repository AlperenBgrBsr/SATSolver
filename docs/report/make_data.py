#!/usr/bin/env python3
"""Turn the experiment outputs into the small files the report reads.

Everything under data/, tables/ and numbers.tex is generated here, never typed
by hand: rerun an experiment, rerun this, recompile, and every figure, table
and number in the text follows. Upload docs/report/ to Overleaf as it is - the
generated files are plain CSV and LaTeX.

  python3 docs/report/make_data.py

Inputs (all produced by the scripts in tests/):
  tests/cost_model.csv                      cost_model.py collect
  tests/memory_sweep.csv                    memory_sweep.py run
  tests/proof_cost.csv                      proof_cost.py
  tests/shuffled/php9_8.luck-*.csv          luck_test.py
  src/php.sample.txt, src/rand.sample.txt   sample, pre-counter binary
  prof/pad0.sample.txt, prof/pad2048.sample.txt   sample, current binary
  data/ladder.txt                           latency_ladder output; built and run
                                            here if missing (takes ~2 minutes)
"""
import csv
import math
import os
import re
import statistics
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TESTS = os.path.join(ROOT, "tests")
sys.path.insert(0, TESTS)
import cost_model as cm      # noqa: E402
import luck_test as lt       # noqa: E402
import memory_sweep as ms    # noqa: E402

DATA = os.path.join(HERE, "data")
TABLES = os.path.join(HERE, "tables")


def need(path):
    if not os.path.exists(path):
        sys.exit("missing input: %s" % os.path.relpath(path, ROOT))
    return path


def write_csv(name, header, rows):
    with open(os.path.join(DATA, name), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)
    print("  data/%s" % name)


def write_tex(path, text):
    with open(path, "w") as fh:
        fh.write("% generated by make_data.py - do not edit by hand\n" + text)
    print("  %s" % os.path.relpath(path, HERE))


# --- profiles ----------------------------------------------------------------

# Source lines of each region in propagate(). The counters moved the code, so
# the two binaries need different maps.
OLD_REGIONS = [("search", {383, 384, 385, 386}), ("reach", {372, 373}), ("unattr", {0}),
               ("skip", {376, 377}), ("walk", {366, 367, 368, 369, 370}), ("move", {387}),
               ("unitconf", set(range(396, 416)))]
NEW_REGIONS = [("search", {411, 412, 413, 414}), ("reach", {397, 398, 399}), ("unattr", {0}),
               ("skip", {402, 403, 404, 405}), ("walk", {390, 391, 392, 393, 394, 395}),
               ("move", {415}), ("unitconf", set(range(429, 453)))]
REGION_LABEL = {"search": "replacement search", "reach": "reach the clause",
                "unattr": "unattributed", "skip": "already satisfied",
                "walk": "watch-list walk", "move": "move the watch",
                "unitconf": "unit / conflict"}


def profile_shares(path, regions):
    txt = open(need(path)).read()
    total = int(re.search(r"^\s*(\d+) Thread_", txt, re.M).group(1))
    per = {}
    for n, ln in re.findall(r"^\s*\+ (\d+) SATSolver::propagate\(\).*SATSolver\.cpp:(\d+)$",
                            txt, re.M):
        per[int(ln)] = per.get(int(ln), 0) + int(n)
    fn = re.search(r"Sort by top of stack.*?\n(.*?)\n\n", txt, re.S)
    funcs = {}
    if fn:
        for line in fn.group(1).splitlines():
            m = re.match(r"\s*(\S.*?)\s+\(in .*?\)\s+(\d+)$", line)
            if m:
                funcs[m.group(1)] = int(m.group(2))
    shares = {k: 100.0 * sum(v for l, v in per.items() if l in lines) / total
              for k, lines in regions}
    return shares, funcs, total


# --- main --------------------------------------------------------------------

def main():
    os.makedirs(DATA, exist_ok=True)
    os.makedirs(TABLES, exist_ok=True)
    nums = {}
    print("writing:")

    # Figure 1: where the time goes, php vs rand3 (same pre-counter binary).
    php, php_fn, php_total = profile_shares(os.path.join(ROOT, "src", "php.sample.txt"), OLD_REGIONS)
    rnd, _, _ = profile_shares(os.path.join(ROOT, "src", "rand.sample.txt"), OLD_REGIONS)
    order = ["walk", "move", "unitconf", "skip", "unattr", "reach", "search"]   # bottom to top
    write_csv("regions.csv", ["idx", "php", "rand"],
              [[i + 1, "%.2f" % php[k], "%.2f" % rnd[k]] for i, k in enumerate(order)])
    write_tex(os.path.join(TABLES, "region_labels.tex"),
              "\\pgfplotsset{regionticks/.style={ytick={1,...,%d},yticklabels={%s}}}\n"
              % (len(order), ",".join(REGION_LABEL[k] for k in order)))
    prop = next((v for k, v in php_fn.items() if "propagate" in k), 0)
    ana = next((v for k, v in php_fn.items() if "analyze" in k), 0)
    nums["PropagateShare"] = "%.1f" % (100.0 * prop / php_total)
    nums["AnalyzeShare"] = "%.1f" % (100.0 * ana / php_total)
    nums["SearchSharePhp"] = "%.0f" % php["search"]
    nums["SearchShareRand"] = "%.0f" % rnd["search"]

    # Figure 2 and the coefficient table: the cost model, fitted on everything.
    rows = [ms.to_numbers(r) for r in cm.load_csv(need(os.path.join(TESTS, "cost_model.csv")))]
    for r in rows:
        r["reduce_first"] = int(r["reduce_first"])
    used = [r for r in rows if r["cycles"] >= 4e8]
    coef = cm.fit_rows(used, False)
    errs = []
    for fam in ["php", "full", "rand"]:
        out = []
        for r in used:
            if r["family"] != fam:
                continue
            p = cm.predict(r, coef, False)
            errs.append(abs(p - r["cycles"]) / r["cycles"])
            out.append(["%.4f" % (r["cycles"] / 1e9), "%.4f" % (p / 1e9)])
        write_csv("costmodel_%s.csv" % fam, ["measured", "predicted"], out)
    names = ["skip", "search", "scan", "conflict"]
    loo = []
    for inst in sorted({r["inst"] for r in used}):
        loo.append(cm.fit_rows([r for r in used if r["inst"] != inst], False))
    lines = []
    desc = {"skip": "visit, clause already satisfied", "search": "visit that searches for a new watch",
            "scan": "literal checked by a search", "conflict": "conflict"}
    for i, n in enumerate(names):
        lo, hi = min(c[i] for c in loo), max(c[i] for c in loo)
        fmt = "%.0f" if n == "conflict" else "%.1f"
        lines.append("%s & %s & [%s, %s] \\\\" % (desc[n], fmt % coef[i], fmt % lo, fmt % hi))
    write_tex(os.path.join(TABLES, "cost_coefficients.tex"), "\n".join(lines) + "\n\\bottomrule\n")
    nums.update(CoefSkip="%.1f" % coef[0], CoefSearch="%.1f" % coef[1],
                CoefScan="%.1f" % coef[2], CoefConflict="%.0f" % coef[3],
                ModelRuns=str(len(used)), ModelMedianErr="%.1f" % (100 * statistics.median(errs)))

    # Visit outcomes at the default schedule, from the same runs.
    lines = []
    for inst in ["php10_9", "php11_10", "rand3_250_s1", "rand3_250_s3", "full17"]:
        r = next((x for x in rows if x["inst"] == inst and x["reduce_first"] == 2000), None)
        if r is None:
            continue
        v = r["clause_visits"]
        search = r["visit_moved"] + r["visit_unit"] + r["visit_conflict"]
        lines.append("\\texttt{%s} & %.1f & %.1f & %.2f & %.3f & %.1f \\\\" % (
            inst.replace("_", "\\_"), 100 * r["visit_skip"] / v, 100 * r["visit_moved"] / v,
            100 * r["visit_unit"] / v, 100 * r["visit_conflict"] / v, r["scan_lits"] / search))
    write_tex(os.path.join(TABLES, "visit_outcomes.tex"), "\n".join(lines) + "\n\\bottomrule\n")

    # Figure 3, left: the latency ladder.
    ladder_txt = os.path.join(DATA, "ladder.txt")
    if not os.path.exists(ladder_txt):
        print("  (running the latency ladder, about 2 minutes)")
        binary = os.path.join(HERE, "data", "latency_ladder")
        subprocess.run(["clang", "-O2", "-o", binary, os.path.join(TESTS, "latency_ladder.c")],
                       check=True)
        with open(ladder_txt, "w") as fh:
            subprocess.run([binary], stdout=fh, check=True)
        os.remove(binary)
    ladder = re.findall(r"^\s*(\d+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*$",
                        open(ladder_txt).read(), re.M)
    write_csv("ladder.csv", ["kb", "random", "inorder"], [[k, rc, ic] for k, _, rc, _, ic in ladder])

    # Figure 3, right: the padding sweep against the in-L2 cost model.
    msw = [ms.to_numbers(r) for r in cm.load_csv(need(os.path.join(TESTS, "memory_sweep.csv")))]
    coef_l2 = ms.in_l2_model(os.path.join(TESTS, "cost_model.csv"), 16384, 4e8)
    for inst in ["php11_10", "rand3_250_s3"]:
        out = []
        for r in msw:
            if r["inst"] != inst:
                continue
            avg = r["learnt_lits"] / max(r["learnts"], 1)
            block = ((4 * (avg + r["pad"]) + 15) // 16) * 16
            est_mb = r["max_learnts"] * (32 + block + 8) / 2 ** 20
            pred = cm.predict(r, coef_l2, False)
            out.append([r["pad"], "%.2f" % est_mb, "%.2f" % (r["rss_kb"] / 1024),
                        "%.3f" % (r["cycles"] / r["clause_visits"]),
                        "%.3f" % ((r["cycles"] - pred) / r["clause_visits"]),
                        "%.3f" % (r["instructions"] / r["cycles"])])
        write_csv("memory_%s.csv" % inst, ["pad", "estmb", "rssmb", "cpv", "excess", "ipc"], out)
    p0 = next(r for r in msw if r["inst"] == "php11_10" and r["pad"] == 0)
    pmax = max((r for r in msw if r["inst"] == "php11_10"), key=lambda r: r["pad"])
    nums["PadSlowdown"] = "%.0f" % (100 * ((pmax["cycles"] / pmax["clause_visits"]) /
                                           (p0["cycles"] / p0["clause_visits"]) - 1))
    nums["PadFootprint"] = "%.0f" % (pmax["rss_kb"] / p0["rss_kb"])

    # Region shift under padding, in cycles per visit (current binary).
    a, _, _ = profile_shares(os.path.join(ROOT, "prof", "pad0.sample.txt"), NEW_REGIONS)
    b, _, _ = profile_shares(os.path.join(ROOT, "prof", "pad2048.sample.txt"), NEW_REGIONS)
    ca, cb = p0["cycles"] / p0["clause_visits"], pmax["cycles"] / pmax["clause_visits"]
    lines = []
    for k in ["search", "unattr", "skip", "reach", "walk", "move"]:
        x, y = a[k] * ca / 100, b[k] * cb / 100
        lines.append("%s & %.1f & %.1f & %+.1f \\\\" % (REGION_LABEL[k], x, y, y - x))
    write_tex(os.path.join(TABLES, "region_shift.tex"), "\n".join(lines) + "\n\\bottomrule\n")

    # Figures 4 and 5: the MiniSat comparison over 50 shuffled copies of php9_8.
    sh = os.path.join(TESTS, "shuffled")
    configs = [("", "MiniSat"), ("-norestart", "no restarts"),
               ("-norestart-nomin", "no restarts, no minim.")]
    out, luck_cols = [], {}
    for i, (tag, _) in enumerate(configs):
        row = [i + 1]
        for orient in ["flip", "noflip"]:
            rws = lt.load_csv(need(os.path.join(sh, "php9_8.luck-%s%s.csv" % (orient, tag))))
            ratios = [int(r["nopre_conf"]) / int(r["sat_conf"]) for r in rws]
            med = statistics.median(ratios)
            lo, hi = lt.bootstrap_median_ci(ratios)
            row += ["%.3f" % med, "%.3f" % (hi - med), "%.3f" % (med - lo)]
            nums["Gap%s%s" % (orient.capitalize(), ["Full", "NoRestart", "NoRestartNoMin"][i])] = \
                "%.2f" % med
            luck_cols["ms%s_%s" % (tag.replace("-", ""), orient)] = [int(r["nopre_conf"]) for r in rws]
            luck_cols["sat_%s" % orient] = [int(r["sat_conf"]) for r in rws]
        out.append(row)
    write_csv("ablation.csv", ["x", "flip", "flipplus", "flipminus",
                               "noflip", "noflipplus", "noflipminus"], out)
    keys = ["sat_flip", "sat_noflip", "ms_flip", "ms_noflip", "msnorestart_flip", "msnorestart_noflip"]
    n = min(len(luck_cols[k]) for k in keys)
    write_csv("luck.csv", keys, [[luck_cols[k][i] for k in keys] for i in range(n)])

    # Proof cost table.
    pc = list(csv.DictReader(l for l in open(need(os.path.join(TESTS, "proof_cost.csv")))
                             if not l.startswith("#")))
    # proof_cost.csv keeps cycles, not wall time: convert with the median
    # effective clock measured across the cost-model runs.
    ghz = statistics.median(r["cycles"] / r["wall"] for r in used) / 1e9
    lines = []
    for r in pc:
        base_s = int(r["base_cycles"]) / (ghz * 1e9)
        lines.append("\\texttt{%s} & %s & %+.1f\\%% & %.1f & %.2f & %.1f \\\\" % (
            r["inst"].replace("_", "\\_"), r["conflicts"], float(r["overhead_pct"]),
            int(r["proof_bytes"]) / 2 ** 20, float(r["check_sec"]),
            float(r["check_sec"]) / base_s))
    write_tex(os.path.join(TABLES, "proof_cost.tex"), "\n".join(lines) + "\n\\bottomrule\n")
    ov = [float(r["overhead_pct"]) for r in pc]
    nums["ProofOverheadMin"], nums["ProofOverheadMax"] = "%.0f" % min(ov), "%.0f" % max(ov)

    write_tex(os.path.join(HERE, "numbers.tex"),
              "".join("\\newcommand{\\num%s}{%s}\n" % (k, v) for k, v in sorted(nums.items())))
    print("\ndone.")


if __name__ == "__main__":
    main()
